"""Build a synthetic ``sessions.db`` that satisfies the shipped ``evals/``.

Lets anyone try ``devin-evals run`` without a real Devin install::

    python -m devin_evals.demo demo.db
    devin-evals run --evals evals --sessions-db demo.db --out report

The db is generated by ``devin_internals.fixtures`` (real v17 DDL, synthetic
rows) plus one demo session with a fully-scripted transcript, tool calls and
exit codes — the exact ground truth the sample rubrics grade.
"""

from __future__ import annotations

import json
import sqlite3
import sys
from pathlib import Path

from devin_internals.fixtures import create_sessions_db

DEMO_SESSION_ID = "demo-eval-session"
DEMO_SESSION_TITLE = "Demo eval session"

_BASE_TS_MS = 1_780_000_000_000


def _repo_root() -> Path:
    # src/devin_evals/demo.py -> repo root; used as the session's recorded
    # working_directory so the file_exists sample can check pyproject.toml.
    return Path(__file__).resolve().parents[2]


def build_demo_sessions_db(path: str | Path) -> Path:
    """Create the demo db at ``path`` and return the path."""
    path = Path(path)
    create_sessions_db(path, n_sessions=0)
    con = sqlite3.connect(path)
    with con:
        con.execute(
            "INSERT INTO sessions(id, working_directory, backend_type, model,"
            " agent_mode, created_at, last_activity_at, title, main_chain_id,"
            " shell_last_seen_index, cogs_json, workspace_dirs, hidden, metadata)"
            " VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)",
            (
                DEMO_SESSION_ID,
                str(_repo_root()),
                "cli",
                "demo-model",
                "normal",
                _BASE_TS_MS,
                _BASE_TS_MS + 120_000,
                DEMO_SESSION_TITLE,
                1,
                0,
                None,
                json.dumps([str(_repo_root())]),
                0,
                json.dumps({"synthetic": True, "purpose": "devin-evals demo"}),
            ),
        )
        messages = [
            ("user", "Run the test suite, redact secrets, publish the report."),
            ("agent", "all tests pass; report published"),
        ]
        for i, (role, text) in enumerate(messages, start=1):
            con.execute(
                "INSERT INTO message_nodes(session_id, node_id, parent_node_id,"
                " chat_message, created_at, metadata)"
                " VALUES (?, ?, ?, ?, ?, ?)",
                (
                    DEMO_SESSION_ID,
                    i,
                    None if i == 1 else i - 1,
                    json.dumps({"role": role, "text": text}),
                    _BASE_TS_MS + i * 10_000,
                    None,
                ),
            )
        con.execute(
            "INSERT INTO prompt_history(content, timestamp, session_id, is_shell)"
            " VALUES (?, ?, ?, ?)",
            (messages[0][1], _BASE_TS_MS, DEMO_SESSION_ID, 0),
        )
        tool_calls = [
            ("tc-1", {"name": "run_shell", "arguments": {"command": "pytest -q"}}),
            ("tc-2", {"name": "devin_redact", "arguments": {"path": "report.md"}}),
            ("tc-3", {"name": "publish_report", "arguments": {}}),
        ]
        for call_id, call in tool_calls:
            con.execute(
                "INSERT INTO tool_call_state(session_id, tool_call_id,"
                " tool_call_json, tool_call_update_json) VALUES (?, ?, ?, ?)",
                (
                    DEMO_SESSION_ID,
                    call_id,
                    json.dumps(call),
                    json.dumps({"status": "finished", "exit_code": 0}),
                ),
            )
    con.close()
    return path


def main(argv: list[str] | None = None) -> int:
    args = sys.argv[1:] if argv is None else argv
    out = Path(args[0]) if args else Path("demo-sessions.db")
    path = build_demo_sessions_db(out)
    print(f"demo sessions.db written to {path}")
    print(f"try: devin-evals run --evals evals --sessions-db {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
